export function wineTags(wine: Wine): TypeTag[] {
  return wine.sparkling ? [...wine.colors, "penusavo"] : [...wine.colors];
}

export function uniqueInOrder(values: string[]): string[] {
  const seen = new Set<string>();
  const result: string[] = [];
  for (const value of values) {
    if (seen.has(value)) continue;
    seen.add(value);
    result.push(value);
  }
  return result;
}

export const countries = uniqueInOrder(wines.map((wine) => wine.country));

export const shops = uniqueInOrder(wines.map((wine) => wine.shop));
